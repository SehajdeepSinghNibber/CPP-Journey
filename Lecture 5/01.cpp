#include <bits/stdc++.h>
using namespace std;

int main(){
    
    int a = 4;
    int b = 6;

    cout<<"a&b:"<<(a&b)<<endl;
    cout<<"a|b:"<<(a|b)<<endl;
    cout<<"~a:"<<(~a)<<endl;
    cout<<"~b:"<<(~b)<<endl;
    cout<<"a^b:"<<(a^b)<<endl;

    cout<<(5>>1)<<endl; // 2
    cout<<(10>>2)<<endl; // 2
    cout<<(10<<1)<<endl; // 20
    cout<<(10<<2)<<endl; // 40

    return 0;
}